// Package manifestkeys generates doctl's agent manifest key tree from the
// flat agent manifest JSON schema, so the tree is never edited by hand.
package manifestkeys

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// Generate returns the Go source of the key tree for schema (the contents of
// testdata/agent.flat.schema.json). The output is gofmt-formatted and
// deterministic.
func Generate(schema []byte) ([]byte, error) {
	closed := map[string][]string{}
	if err := walk(schema, schema, "", closed); err != nil {
		return nil, err
	}
	if _, ok := closed[""]; !ok {
		return nil, fmt.Errorf("schema has no closed root object")
	}

	paths := make([]string, 0, len(closed))
	for p := range closed {
		paths = append(paths, p)
	}
	sort.Slice(paths, func(i, j int) bool {
		if (paths[i] == "") != (paths[j] == "") {
			return paths[i] == ""
		}
		return paths[i] < paths[j]
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by commands/internal/manifestkeys from testdata/agent.flat.schema.json; DO NOT EDIT.\n")
	b.WriteString("// Refresh with `go generate ./commands` after updating the schema copy.\n\n")
	b.WriteString("package commands\n\nvar (\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%s = &keyNode{keys: []keyDef{\n", varName(p))
		for _, k := range closed[p] {
			kind, child := classify(closed, p, k)
			switch kind {
			case "":
				fmt.Fprintf(&b, "\t\t{name: %q},\n", k)
			case "keyTools":
				fmt.Fprintf(&b, "\t\t{name: %q, kind: keyTools},\n", k)
			default:
				fmt.Fprintf(&b, "\t\t{name: %q, kind: %s, child: %s},\n", k, kind, varName(child))
			}
		}
		b.WriteString("\t}}\n")
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

func joinPath(parent, key string) string {
	if parent == "" {
		return key
	}
	return parent + "." + key
}

// classify says what key k of the closed object at path holds, from which
// closed-object paths the schema walk found beneath it.
func classify(closed map[string][]string, path, k string) (kind, childPath string) {
	child := joinPath(path, k)
	if _, ok := closed[child+"[]."+"{catalog}"]; ok {
		return "keyTools", ""
	}
	for _, c := range []struct{ suffix, kind string }{
		{"", "keyObject"},
		{"[]", "keyObjectList"},
		{".*", "keyMapOfObjects"},
	} {
		if _, ok := closed[child+c.suffix]; ok {
			return c.kind, child + c.suffix
		}
	}
	return "", ""
}

// varName is the Go name of the node at path. The two tools nodes keep fixed
// names because the tools walker refers to them directly.
func varName(path string) string {
	switch path {
	case "":
		return "manifestRootKeys"
	case "tools[]":
		return "manifestToolInlineKeys"
	case "tools[].{catalog}":
		return "manifestToolCatalogKeys"
	}
	var b strings.Builder
	b.WriteString("manifest")
	for _, seg := range strings.FieldsFunc(path, func(r rune) bool { return r == '.' || r == '_' || r == '[' || r == ']' }) {
		switch seg {
		case "*":
			b.WriteString("Value")
		case "{catalog}":
			b.WriteString("Catalog")
		default:
			b.WriteString(strings.ToUpper(seg[:1]) + seg[1:])
		}
	}
	b.WriteString("Keys")
	return b.String()
}

type schemaNode struct {
	Properties           json.RawMessage            `json:"properties"`
	AdditionalProperties json.RawMessage            `json:"additionalProperties"`
	PatternProperties    map[string]json.RawMessage `json:"patternProperties"`
	Items                json.RawMessage            `json:"items"`
	OneOf                []json.RawMessage          `json:"oneOf"`
	AnyOf                []json.RawMessage          `json:"anyOf"`
	AllOf                []json.RawMessage          `json:"allOf"`
	Ref                  string                     `json:"$ref"`
	Then                 json.RawMessage            `json:"then"`
	Else                 json.RawMessage            `json:"else"`
}

// walk records the property names (in schema order) of every closed object
// (additionalProperties: false with properties), keyed by path: "a.b" for a
// nested object, "a[]" for list items, "a.*" for the object value of a
// free-keyed map and "tools[].{catalog}" for a catalog selection's value. It
// follows properties, items, oneOf/anyOf/allOf, schema-valued
// additionalProperties, patternProperties and local $ref targets. The egress
// object is skipped: validateEgressObject checks it.
func walk(root, raw json.RawMessage, path string, out map[string][]string) error {
	if path == "egress" {
		return nil
	}
	var n schemaNode
	if err := json.Unmarshal(raw, &n); err != nil {
		return fmt.Errorf("path %q: %w", path, err)
	}
	// if/then/else only constrain values; a closed object there would hold
	// keys the server accepts but this tree cannot see, so refuse it.
	for _, branch := range []json.RawMessage{n.Then, n.Else} {
		if len(branch) == 0 || string(bytes.TrimSpace(branch)) == "false" {
			continue
		}
		var br schemaNode
		if json.Unmarshal(branch, &br) == nil && len(br.Properties) > 0 && string(bytes.TrimSpace(br.AdditionalProperties)) == "false" {
			return fmt.Errorf("a then/else branch at %q declares a closed object; extend the generator to follow it", path)
		}
	}
	if n.Ref != "" {
		target, err := resolveRef(root, n.Ref)
		if err != nil {
			return err
		}
		if err := walk(root, target, path, out); err != nil {
			return err
		}
	}
	if len(n.Properties) > 0 {
		order, err := keyOrder(n.Properties)
		if err != nil {
			return fmt.Errorf("path %q: %w", path, err)
		}
		var props map[string]json.RawMessage
		if err := json.Unmarshal(n.Properties, &props); err != nil {
			return err
		}
		if string(bytes.TrimSpace(n.AdditionalProperties)) == "false" {
			if _, dup := out[path]; dup {
				return fmt.Errorf("two closed objects at %q", path)
			}
			out[path] = order
		}
		for _, k := range order {
			if err := walk(root, props[k], joinPath(path, k), out); err != nil {
				return err
			}
		}
	}
	if len(n.Items) > 0 {
		if err := walk(root, n.Items, path+"[]", out); err != nil {
			return err
		}
	}
	if ap := bytes.TrimSpace(n.AdditionalProperties); len(ap) > 0 && ap[0] == '{' {
		if err := walk(root, n.AdditionalProperties, path+".*", out); err != nil {
			return err
		}
	}
	if len(n.PatternProperties) > 0 {
		if len(n.PatternProperties) != 1 {
			return fmt.Errorf("path %q: expected one patternProperties entry", path)
		}
		for pattern, sub := range n.PatternProperties {
			if !strings.HasPrefix(pattern, `^do\.`) {
				return fmt.Errorf("unexpected pattern %q at %q", pattern, path)
			}
			if err := walk(root, sub, path+".{catalog}", out); err != nil {
				return err
			}
		}
	}
	for _, branches := range [][]json.RawMessage{n.OneOf, n.AnyOf, n.AllOf} {
		for _, br := range branches {
			if err := walk(root, br, path, out); err != nil {
				return err
			}
		}
	}
	return nil
}

func keyOrder(raw json.RawMessage) ([]string, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	if tok, err := dec.Token(); err != nil || tok != json.Delim('{') {
		return nil, fmt.Errorf("not a JSON object")
	}
	var keys []string
	for dec.More() {
		kt, err := dec.Token()
		if err != nil {
			return nil, err
		}
		keys = append(keys, kt.(string))
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return nil, err
		}
	}
	return keys, nil
}

func resolveRef(root json.RawMessage, ref string) (json.RawMessage, error) {
	if !strings.HasPrefix(ref, "#/") {
		return nil, fmt.Errorf("only local $ref is supported, got %q", ref)
	}
	cur := root
	for _, part := range strings.Split(strings.TrimPrefix(ref, "#/"), "/") {
		var m map[string]json.RawMessage
		if err := json.Unmarshal(cur, &m); err != nil {
			return nil, fmt.Errorf("resolving %q: %w", ref, err)
		}
		next, ok := m[part]
		if !ok {
			return nil, fmt.Errorf("$ref %q: no %q", ref, part)
		}
		cur = next
	}
	return cur, nil
}
